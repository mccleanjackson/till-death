// Builds the PRIVATE seed SQL (story + invite codes) from ../private/story.json.
// Output goes to ../private/seed.sql — outside the repo, never commit it.
// The story is base64-encoded inside the SQL so pasting it into Supabase doesn't spoil anything.
//
// Usage: node scripts/make-seed.mjs [--host avery] [--url https://you.github.io/till-death/]
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { randomInt } from 'node:crypto';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { checkStory } from './story-check.mjs';

const here = dirname(fileURLToPath(import.meta.url));
const privateDir = process.env.TD_PRIVATE_DIR || resolve(here, '../../private');
const arg = (name, dflt) => { const i = process.argv.indexOf(`--${name}`); return i > 0 ? process.argv[i + 1] : dflt; };
const hostRole = arg('host', 'avery');
const siteUrl = arg('url', 'http://localhost:5173/').replace(/\/?$/, '/');

const storyPath = resolve(privateDir, 'story.json');
if (!existsSync(storyPath)) throw Error(`Missing ${storyPath}`);
const stories = {
  party: JSON.parse(readFileSync(storyPath, 'utf8')),
  practice: JSON.parse(readFileSync(resolve(here, 'demo-story.json'), 'utf8')),
};
// Optional 12-player version of the party story (adds an accomplice and one more guest).
const story12Path = resolve(privateDir, 'story12.json');
if (existsSync(story12Path)) stories.party12 = JSON.parse(readFileSync(story12Path, 'utf8'));
// Christmas family game (8 solo players, no couples).
const xmasPath = resolve(privateDir, 'xmas.json');
if (existsSync(xmasPath)) stories.xmas = JSON.parse(readFileSync(xmasPath, 'utf8'));
// Each game plays one of the stories. party2/practice2 are a second, independent copy for another host.
const GAMES = { party: 'party', practice: 'practice', party2: stories.party12 ? 'party12' : 'party', practice2: 'practice', ...(stories.xmas ? { xmas: 'xmas' } : {}) };
const problems = Object.entries(stories).flatMap(([k, s]) => checkStory(s, k));
if (problems.length) { console.error(problems.join('\n')); process.exit(1); }
// Games where the host plays a random seat (they may end up as the culprit or accomplice).
// The pick is saved in hosts.json so re-running the seed never moves the host.
const RANDOM_HOST = new Set(['xmas']);
const hostsPath = resolve(privateDir, 'hosts.json');
const hosts = existsSync(hostsPath) ? JSON.parse(readFileSync(hostsPath, 'utf8')) : {};
for (const g of RANDOM_HOST) if (GAMES[g]) {
  const ids = stories[GAMES[g]].roles.map(r => r.id);
  if (!ids.includes(hosts[g])) hosts[g] = ids[randomInt(ids.length)];
}
writeFileSync(hostsPath, JSON.stringify(hosts, null, 2));
const hostOf = game => (RANDOM_HOST.has(game) ? hosts[game] : hostRole);

for (const [k, st] of Object.entries(stories)) {
  if (Object.entries(GAMES).every(([g, sid]) => sid !== k || RANDOM_HOST.has(g))) continue;
  if (!st.roles.some(r => r.id === hostRole)) { console.error(`--host ${hostRole} is not a role in ${k}`); process.exit(1); }
  if ([st.solution.killer, st.solution.accomplice].includes(hostRole) || st.roles.find(r => r.id === hostRole).optional) {
    console.error(`The host can't be the culprit, the accomplice or an optional seat in ${k}. Pick a different --host.`);
    process.exit(1);
  }
}

// Invite codes are generated once and reused, so re-running the seed never breaks links already sent.
const ALPHABET = 'ABCDEFGHJKLMNPQRSTUVWXYZ23456789';
const newCode = () => Array.from({ length: 6 }, () => ALPHABET[randomInt(ALPHABET.length)]).join('');
const codesPath = resolve(privateDir, 'codes.json');
const codes = existsSync(codesPath) ? JSON.parse(readFileSync(codesPath, 'utf8')) : {};
const used = new Set(Object.values(codes).flatMap(Object.values));
const roleIds = game => stories[GAMES[game]].roles.map(r => r.id);
for (const game of Object.keys(GAMES)) {
  codes[game] ??= {};
  for (const id of roleIds(game)) {
    if (!codes[game][id]) { let c; do c = newCode(); while (used.has(c)); used.add(c); codes[game][id] = c; }
  }
}
writeFileSync(codesPath, JSON.stringify(codes, null, 2));

const q = s => `'${String(s).replace(/'/g, "''")}'`;
let sql = '-- PRIVATE. Generated by scripts/make-seed.mjs. Do not commit or share.\n-- Run AFTER supabase/schema.sql. Safe to re-run.\nbegin;\n';
for (const [id, story] of Object.entries(stories)) {
  const blob = Buffer.from(JSON.stringify(story), 'utf8').toString('base64');
  sql += `insert into td_private.stories (id, blob) values (${q(id)}, ${q(blob)}) on conflict (id) do update set blob = excluded.blob;\n`;
}
for (const [game, storyId] of Object.entries(GAMES)) {
  // A game may switch story only while it is still in the lobby.
  sql += `insert into td_private.games (id, story_id) values (${q(game)}, ${q(storyId)}) on conflict (id) do update set story_id = excluded.story_id where td_private.games.phase = 0;\n`;
  for (const id of roleIds(game)) {
    sql += `insert into td_private.players (code, game_id, role_id, is_host) values (${q(codes[game][id])}, ${q(game)}, ${q(id)}, ${id === hostOf(game)}) on conflict (code) do update set is_host = excluded.is_host;\n`;
  }
  sql += `update td_private.games set version = version + 1 where id = ${q(game)};\n`;
}
sql += 'commit;\n';
writeFileSync(resolve(privateDir, 'seed.sql'), sql);

console.log(`Wrote ${resolve(privateDir, 'seed.sql')}`);
console.log(`Host (${hostRole}) links — the host screen in the app shows everyone else's links:`);
console.log(`  Practice game: ${siteUrl}#/j/${codes.practice[hostRole]}`);
console.log(`  Party game:    ${siteUrl}#/j/${codes.party[hostRole]}`);
if (codes.xmas) console.log(`  Christmas game: ${siteUrl}#/j/${codes.xmas[hostOf('xmas')]}`);
console.log(`  Second host — practice: ${siteUrl}#/j/${codes.practice2[hostRole]}`);
console.log(`  Second host — party:    ${siteUrl}#/j/${codes.party2[hostRole]}`);
